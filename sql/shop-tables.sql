-- Santiano shop tables (users, orders, reviews, discount codes, notifications, support, settings, accounting).
-- The server runs this automatically on start when DATABASE_URL is set, so you do not have to.
-- Safe to run more than once. Timestamps are UTC text ('YYYY-MM-DD HH:MM:SS') so dates behave the same as before.

create table if not exists public.users (
  id            integer generated by default as identity primary key,
  role          text not null check (role in ('customer','admin')),
  name          text not null,
  email         text not null unique,
  phone         text,
  password_hash text not null,
  address       text,
  suspended     integer not null default 0,
  reset_token   text,
  reset_expires text,
  created_at    text not null default to_char(now() at time zone 'utc','YYYY-MM-DD HH24:MI:SS')
);

-- product_id is the id in public.products (no foreign key, so a product can be deleted without losing its reviews/orders)
create table if not exists public.reviews (
  id         integer generated by default as identity primary key,
  product_id integer not null,
  user_id    integer not null references public.users(id) on delete cascade,
  rating     integer not null check (rating between 1 and 5),
  title      text,
  body       text,
  created_at text not null default to_char(now() at time zone 'utc','YYYY-MM-DD HH24:MI:SS'),
  unique (product_id, user_id)
);
create index if not exists idx_reviews_product on public.reviews(product_id);

create table if not exists public.orders (
  id             integer generated by default as identity primary key,
  reference      text not null unique,
  customer_id    integer references public.users(id) on delete set null,
  customer_name  text not null,
  customer_phone text not null,
  customer_email text not null,
  method         text not null default 'delivery',
  address        text,
  subtotal       double precision not null,
  delivery_fee   double precision not null default 0,
  discount       double precision not null default 0,
  discount_code  text,
  total          double precision not null,
  status         text not null default 'pending_payment',
  note           text,
  refund_ref     text,
  paid_at        text,
  created_at     text not null default to_char(now() at time zone 'utc','YYYY-MM-DD HH24:MI:SS')
);
create index if not exists idx_orders_customer on public.orders(customer_id);

create table if not exists public.order_items (
  id         integer generated by default as identity primary key,
  order_id   integer not null references public.orders(id) on delete cascade,
  product_id integer,
  name       text not null,
  variant    text,
  image      text,
  qty        integer not null,
  unit_price double precision not null,
  unit_cost  double precision
);
create index if not exists idx_order_items_order on public.order_items(order_id);

create table if not exists public.discount_codes (
  id         integer generated by default as identity primary key,
  code       text not null unique,
  kind       text not null check (kind in ('percent','fixed')),
  value      double precision not null,
  min_order  double precision not null default 0,
  max_uses   integer,
  used       integer not null default 0,
  expires_on text,
  active     integer not null default 1
);

create table if not exists public.notifications (
  id         integer generated by default as identity primary key,
  user_id    integer not null references public.users(id) on delete cascade,
  title      text not null,
  body       text,
  link       text,
  is_read    integer not null default 0,
  created_at text not null default to_char(now() at time zone 'utc','YYYY-MM-DD HH24:MI:SS')
);
create index if not exists idx_notifications_user on public.notifications(user_id);

create table if not exists public.support_requests (
  id          integer generated by default as identity primary key,
  user_id     integer not null references public.users(id) on delete cascade,
  subject     text not null,
  message     text not null,
  status      text not null default 'open',
  admin_reply text,
  created_at  text not null default to_char(now() at time zone 'utc','YYYY-MM-DD HH24:MI:SS')
);

create table if not exists public.settings (key text primary key, value text not null);

-- Accounting (admin only). Cost price per product lives here because public.products has no cost column.
create table if not exists public.product_costs (
  product_id integer primary key,
  cost       double precision not null check (cost >= 0),
  updated_at text not null default to_char(now() at time zone 'utc','YYYY-MM-DD HH24:MI:SS')
);
create table if not exists public.expenses (
  id          integer generated by default as identity primary key,
  date        text not null,
  category    text not null,
  description text,
  vendor      text,
  amount      double precision not null check (amount > 0),
  created_at  text not null default to_char(now() at time zone 'utc','YYYY-MM-DD HH24:MI:SS')
);
create index if not exists idx_expenses_date on public.expenses(date);
-- kind: capital, drawing, loan_in, loan_repay, stock_purchase, opening_stock
create table if not exists public.money_entries (
  id          integer generated by default as identity primary key,
  date        text not null,
  kind        text not null,
  description text,
  amount      double precision not null check (amount > 0),
  created_at  text not null default to_char(now() at time zone 'utc','YYYY-MM-DD HH24:MI:SS')
);
create table if not exists public.fixed_assets (
  id            integer generated by default as identity primary key,
  name          text not null,
  cost          double precision not null check (cost > 0),
  purchase_date text not null,
  life_years    double precision not null default 5,
  salvage       double precision not null default 0,
  created_at    text not null default to_char(now() at time zone 'utc','YYYY-MM-DD HH24:MI:SS')
);
create table if not exists public.audit_log (
  id         integer generated by default as identity primary key,
  actor_id   integer,
  action     text not null,
  detail     text,
  created_at text not null default to_char(now() at time zone 'utc','YYYY-MM-DD HH24:MI:SS')
);

-- Lock every table to the public (anon) key. The shop server connects directly as the database owner, which is not affected.
alter table public.users            enable row level security;
alter table public.reviews          enable row level security;
alter table public.orders           enable row level security;
alter table public.order_items      enable row level security;
alter table public.discount_codes   enable row level security;
alter table public.notifications    enable row level security;
alter table public.support_requests enable row level security;
alter table public.settings         enable row level security;
alter table public.product_costs    enable row level security;
alter table public.expenses         enable row level security;
alter table public.money_entries    enable row level security;
alter table public.fixed_assets     enable row level security;
alter table public.audit_log        enable row level security;
